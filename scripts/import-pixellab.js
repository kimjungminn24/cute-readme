import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { decodePng } from '../src/png.js';
import { toAscii } from '../src/ascii.js';

const [dir, ...ids] = process.argv.slice(2);
if (!dir || !ids.length) {
  console.error('usage: node scripts/import-pixellab.js <dir> <id> [<id> ...]');
  process.exit(1);
}

/* Remove pale gray pixels below the last colored pixel in each column. */
function dropShadow(im) {
  const { width: w, height: h, pixels: p } = im;
  const isGray = (i) => {
    const [r, g, b] = [p[i], p[i + 1], p[i + 2]];
    const lum = 0.299 * r + 0.587 * g + 0.114 * b;
    return Math.max(r, g, b) - Math.min(r, g, b) < 14 && lum > 120 && lum < 225;
  };
  let dropped = 0;
  for (let x = 0; x < w; x++) {
    for (let y = h - 1; y >= 0; y--) {
      const i = (y * w + x) * 4;
      if (p[i + 3] < 128) continue;
      if (!isGray(i)) break;
      p[i + 3] = 0; dropped++;
    }
  }
  return dropped;
}

mkdirSync('src/floor-ai', { recursive: true });
for (const id of ids) {
  const im = decodePng(readFileSync(`${dir}/${id}.png`));
  const dropped = dropShadow(im);
  const { rows, palette, trimmed } = toAscii(im);
  const text = `import { sprite, drawAscii } from '../pixel.js';

/* Generated by scripts/import-pixellab.js. */

export const rows = [
${rows.map((r) => `  '${r}',`).join('\n')}
];

export const palette = ${JSON.stringify(palette).replace(/"/g, "'").replace(/,/g, ', ').replace(/:/g, ': ')};

export const art = \`<g transform="scale(0.5)">\${sprite((dots) => drawAscii(dots, rows, palette))}</g>\`;
export const size = { w: ${trimmed.width}, h: ${trimmed.height}, scale: 0.5 };
`;
  writeFileSync(`src/floor-ai/${id}.js`, text);
  console.error(`${id}: ${trimmed.width}x${trimmed.height}칸, 색 ${Object.keys(palette).length}개${dropped ? `, 그림자 ${dropped}px 제거` : ''}`);
}

const all = readdirSync('src/floor-ai').filter((f) => f.endsWith('.js')).map((f) => f.slice(0, -3)).sort();
writeFileSync('src/catalog-floor-ai.js', `/* Generated by scripts/import-pixellab.js. */
${all.map((i) => `export { art as ${i} } from './floor-ai/${i}.js';`).join('\n')}
`);
console.error(`색인 ${all.length}개 → src/catalog-floor-ai.js`);
